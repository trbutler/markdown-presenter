import AppKit
import SwiftUI
import UniformTypeIdentifiers
import PresenterCore

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate {
    private let controller = DeckController()
    private var midiTerminationPending = false
    private var windowManager: WindowManager?
    private var keyRouter: KeyRouter?
    private var preferencesWindow: NSWindow?

    func applicationDidFinishLaunching(_ notification: Notification) {
        buildMainMenu()
        guard let deckURL = resolveDeckURL() else { NSApp.terminate(nil); return }
        let manager = WindowManager(deckURL: deckURL, controller: controller)
        windowManager = manager
        manager.showAll()
        keyRouter = KeyRouter(controller: controller)
        NSApp.activate(ignoringOtherApps: true)
    }

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool { false }
    // VERIFY-ON-MAC: confirm AppKit terminateLater/reply integration on macOS 27.
    // Shutdown waits asynchronously for MIDI queue completion or a 500 ms deadline.
    func applicationShouldTerminate(_ sender: NSApplication) -> NSApplication.TerminateReply {
        guard !midiTerminationPending else { return .terminateLater }
        midiTerminationPending = true
        controller.stopMIDI { [weak self] in
            Task { @MainActor in self?.finishMIDITermination() }
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(500)) { [weak self] in
            self?.finishMIDITermination()
        }
        return .terminateLater
    }

    private func finishMIDITermination() {
        guard midiTerminationPending else { return }
        midiTerminationPending = false
        NSApp.reply(toApplicationShouldTerminate: true)
    }

    func applicationWillTerminate(_ notification: Notification) {
        controller.stopMIDI()
        windowManager?.shutdown()
    }

    private func resolveDeckURL() -> URL? {
        if let path = CommandLine.arguments.dropFirst().first(where: { !$0.hasPrefix("-") }) {
            let url = URL(fileURLWithPath: path).resolvingSymlinksInPath().standardizedFileURL
            if FileManager.default.fileExists(atPath: url.path) { return url }
        }
        let panel = NSOpenPanel()
        panel.message = "Choose a deck generated by generate.pl"
        panel.allowedContentTypes = [.html]
        panel.allowsMultipleSelection = false
        guard panel.runModal() == .OK, let url = panel.url else { return nil }
        return url.resolvingSymlinksInPath().standardizedFileURL
    }

    private func buildMainMenu() {
        let main = NSMenu()
        let app = NSMenu()
        addItem("Preferences…", #selector(showPreferences), ",", to: app)
        app.addItem(.separator())
        app.addItem(withTitle: "Quit PresenterApp", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        addSubmenu(app, title: "PresenterApp", to: main)
        let slides = NSMenu(title: "Slide")
        addItem("Next", #selector(nextSlide), "", to: slides)
        addItem("Previous", #selector(previousSlide), "", to: slides)
        addItem("First", #selector(firstSlide), "", to: slides)
        addItem("Last", #selector(lastSlide), "", to: slides)
        addItem("Black Screen", #selector(toggleBlack), "", to: slides)
        addItem("Reset Timer", #selector(resetTimer), "t", to: slides)
        addItem("Reload Deck", #selector(reloadDeck), "r", to: slides)
        addSubmenu(slides, title: "Slide", to: main)
        let windows = NSMenu(title: "Window")
        addItem("Show All Views", #selector(showAllViews), "0", to: windows)
        addSubmenu(windows, title: "Window", to: main)
        NSApp.windowsMenu = windows
        NSApp.mainMenu = main
    }

    private func addSubmenu(_ menu: NSMenu, title: String, to parent: NSMenu) {
        let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
        item.submenu = menu
        parent.addItem(item)
    }
    private func addItem(_ title: String, _ action: Selector, _ key: String, to menu: NSMenu) {
        let item = NSMenuItem(title: title, action: action, keyEquivalent: key)
        item.target = self
        menu.addItem(item)
    }

    @objc private func showPreferences() {
        guard let manager = windowManager else { return }
        if preferencesWindow == nil {
            // VERIFY-ON-MAC: macOS 27 SwiftUI/AppKit host/window integration.
            let host = NSHostingController(rootView: ViewPreferences(store: manager.store))
            let window = NSWindow(contentViewController: host)
            window.title = "Presenter Preferences"
            window.styleMask = [.titled, .closable, .resizable]
            window.isReleasedWhenClosed = false
            window.center()
            preferencesWindow = window
        }
        preferencesWindow?.makeKeyAndOrderFront(nil)
    }
    @objc private func nextSlide() { controller.perform(.next) }
    @objc private func previousSlide() { controller.perform(.previous) }
    @objc private func firstSlide() { controller.perform(.first) }
    @objc private func lastSlide() { controller.perform(.last) }
    @objc private func toggleBlack() { controller.perform(.toggleBlack) }
    @objc private func resetTimer() { controller.perform(.resetTimer(at: DeckState.nowMillis())) }
    @objc private func reloadDeck() { windowManager?.reloadAll() }
    @objc private func showAllViews() { windowManager?.showAll() }
}
