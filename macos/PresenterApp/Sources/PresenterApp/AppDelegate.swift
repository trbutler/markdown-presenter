import AppKit
import UniformTypeIdentifiers
import PresenterCore

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private let controller = DeckController()
    private var windowManager: WindowManager?
    private var keyRouter: KeyRouter?
    private var overlay: OverlayOutput?
    private let displaysMenu = NSMenu(title: "Displays")
    private let outputMenu = NSMenu(title: "Output")

    func applicationDidFinishLaunching(_ notification: Notification) {
        buildMainMenu()
        guard let deckURL = resolveDeckURL() else {
            NSApp.terminate(nil)
            return
        }
        let manager = WindowManager(deckURL: deckURL, controller: controller)
        windowManager = manager
        manager.showAll()
        keyRouter = KeyRouter(controller: controller)
        NSApp.activate(ignoringOtherApps: true)
    }

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool {
        false
    }

    func applicationWillTerminate(_ notification: Notification) {
        overlay?.stop()
    }

    /// First non-flag argument, else an Open panel.
    private func resolveDeckURL() -> URL? {
        let arguments = CommandLine.arguments.dropFirst()
        if let path = arguments.first(where: { !$0.hasPrefix("-") }) {
            let url = URL(fileURLWithPath: path).standardizedFileURL
            if FileManager.default.fileExists(atPath: url.path) {
                return url
            }
            NSLog("[PresenterApp] deck not found: %@", url.path)
        }
        let panel = NSOpenPanel()
        panel.message = "Choose a deck generated by generate.pl"
        panel.allowedContentTypes = [.html]
        panel.allowsMultipleSelection = false
        return panel.runModal() == .OK ? panel.url : nil
    }

    // MARK: - Menus

    private func buildMainMenu() {
        let main = NSMenu()

        let appMenu = NSMenu()
        appMenu.addItem(withTitle: "Quit PresenterApp", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        addSubmenu(appMenu, titled: "PresenterApp", to: main)

        let slideMenu = NSMenu(title: "Slide")
        addItem("Next", #selector(nextSlide), "", to: slideMenu)
        addItem("Previous", #selector(previousSlide), "", to: slideMenu)
        addItem("First", #selector(firstSlide), "", to: slideMenu)
        addItem("Last", #selector(lastSlide), "", to: slideMenu)
        addItem("Black Screen", #selector(toggleBlack), "", to: slideMenu)
        slideMenu.addItem(.separator())
        addItem("Reset Timer", #selector(resetTimer), "t", to: slideMenu)
        addItem("Reload Deck", #selector(reloadDeck), "r", to: slideMenu)
        addSubmenu(slideMenu, titled: "Slide", to: main)

        displaysMenu.delegate = self
        addSubmenu(displaysMenu, titled: "Displays", to: main)

        outputMenu.delegate = self
        addSubmenu(outputMenu, titled: "Output", to: main)

        let windowMenu = NSMenu(title: "Window")
        addItem("Show All Views", #selector(showAllViews), "0", to: windowMenu)
        windowMenu.addItem(withTitle: "Minimize", action: #selector(NSWindow.performMiniaturize(_:)), keyEquivalent: "m")
        addSubmenu(windowMenu, titled: "Window", to: main)
        NSApp.windowsMenu = windowMenu

        NSApp.mainMenu = main
    }

    private func addSubmenu(_ menu: NSMenu, titled title: String, to parent: NSMenu) {
        let item = NSMenuItem(title: title, action: nil, keyEquivalent: "")
        item.submenu = menu
        parent.addItem(item)
    }

    @discardableResult
    private func addItem(_ title: String, _ action: Selector, _ key: String, to menu: NSMenu) -> NSMenuItem {
        let item = NSMenuItem(title: title, action: action, keyEquivalent: key)
        item.target = self
        menu.addItem(item)
        return item
    }

    /// Displays and Output menus are rebuilt each time they open, so they
    /// always reflect the displays connected right now.
    func menuNeedsUpdate(_ menu: NSMenu) {
        if menu === displaysMenu {
            rebuildDisplaysMenu()
        } else if menu === outputMenu {
            rebuildOutputMenu()
        }
    }

    private func rebuildDisplaysMenu() {
        displaysMenu.removeAllItems()
        guard let manager = windowManager else {
            return
        }
        let displays = NSScreen.displayInfos
        for role in ViewRole.windowed {
            let submenu = NSMenu(title: role.title)
            let saved = manager.assignments.savedDisplayID(for: role)
            let automatic = NSMenuItem(title: "Automatic", action: #selector(assignDisplay(_:)), keyEquivalent: "")
            automatic.target = self
            automatic.representedObject = DisplayChoice(role: role, displayID: nil)
            automatic.state = saved == nil ? .on : .off
            submenu.addItem(automatic)
            submenu.addItem(.separator())
            for display in displays {
                let title = display.name + (display.isPrimary ? " (main)" : "")
                let item = NSMenuItem(title: title, action: #selector(assignDisplay(_:)), keyEquivalent: "")
                item.target = self
                item.representedObject = DisplayChoice(role: role, displayID: display.id)
                if saved == display.id {
                    item.state = .on
                } else if saved == nil && manager.resolvedDisplayID(for: role) == display.id {
                    item.state = .mixed
                }
                submenu.addItem(item)
            }
            if let saved = saved, !displays.contains(where: { $0.id == saved }) {
                let missing = NSMenuItem(title: "Saved display not connected", action: nil, keyEquivalent: "")
                missing.isEnabled = false
                submenu.addItem(missing)
            }
            let parent = NSMenuItem(title: role.title, action: nil, keyEquivalent: "")
            parent.submenu = submenu
            displaysMenu.addItem(parent)
        }
    }

    private func rebuildOutputMenu() {
        outputMenu.removeAllItems()
        if let overlay = overlay {
            let status = NSMenuItem(title: "Overlay running (\(overlay.sinkName), \(overlay.outputWidth)x\(overlay.outputHeight) @ \(Int(overlay.framesPerSecond)) fps)", action: nil, keyEquivalent: "")
            status.isEnabled = false
            outputMenu.addItem(status)
            addItem("Stop Overlay Output", #selector(stopOverlay), "", to: outputMenu)
        } else {
            addItem("Start Overlay Output", #selector(startOverlay), "", to: outputMenu)
        }
        outputMenu.addItem(.separator())
        // NDI attribution, required next to where NDI is offered.
        let attribution = NSMenuItem(title: "NDI\u{00AE} is a registered trademark of Vizrt NDI AB", action: nil, keyEquivalent: "")
        attribution.isEnabled = false
        outputMenu.addItem(attribution)
        addItem("About NDI (ndi.video)", #selector(openNDIWebsite), "", to: outputMenu)
    }

    // MARK: - Actions

    @objc private func nextSlide() { controller.perform(.next) }
    @objc private func previousSlide() { controller.perform(.previous) }
    @objc private func firstSlide() { controller.perform(.first) }
    @objc private func lastSlide() { controller.perform(.last) }
    @objc private func toggleBlack() { controller.perform(.toggleBlack) }
    @objc private func resetTimer() { controller.perform(.resetTimer(at: DeckState.nowMillis())) }

    @objc private func reloadDeck() {
        windowManager?.reloadAll()
    }

    @objc private func showAllViews() {
        windowManager?.showAll()
    }

    @objc private func assignDisplay(_ sender: NSMenuItem) {
        guard let choice = sender.representedObject as? DisplayChoice else {
            return
        }
        windowManager?.assign(choice.role, to: choice.displayID)
    }

    @objc private func startOverlay() {
        guard overlay == nil, let manager = windowManager else {
            return
        }
        let output = OverlayOutput(deckURL: manager.deckURL, controller: controller, sink: makeFrameSink())
        do {
            try output.start()
            overlay = output
        } catch {
            NSLog("[PresenterApp] overlay output failed to start: %@", String(describing: error))
        }
    }

    @objc private func stopOverlay() {
        overlay?.stop()
        overlay = nil
        controller.unregister(.overlay)
    }

    @objc private func openNDIWebsite() {
        if let url = URL(string: "https://ndi.video") {
            NSWorkspace.shared.open(url)
        }
    }

    /// NDI when the runtime is installed and the binding is written; the stub otherwise.
    private func makeFrameSink() -> FrameSink {
        guard NDIFrameSink.bindingImplemented else {
            NSLog("[PresenterApp] using stub frame sink: %@", String(describing: NDIRuntimeError.bindingNotImplemented))
            return StubFrameSink()
        }
        do {
            return NDIFrameSink(runtime: try NDIRuntime.load())
        } catch {
            NSLog("[PresenterApp] using stub frame sink: %@", String(describing: error))
            return StubFrameSink()
        }
    }
}

private struct DisplayChoice {
    let role: ViewRole
    let displayID: String?
}
